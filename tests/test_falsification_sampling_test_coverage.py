class TestFalsifyP3NonThresholdIntegration:
    """
    Probe 3 (Category E — Integration): Non-threshold strategy through VolumeSampler.

    Finding: test_volume_sampler.py only uses sampling_strategy="threshold".
    No test verifies that a non-default strategy (power_law, boltzmann, sigmoid)
    works end-to-end through VolumeSampler.__init__ → _generate_window → get_batch.

    Severity: Soft falsification.

    Fix: Add an integration test that runs VolumeSampler with each non-default strategy.
    """

    def test_power_law_through_volume_sampler(self):
        """VolumeSampler with sampling_strategy='power_law' produces valid batch."""
        from views_hydranet.utils.volume_handler import VolumeHandler
        from views_hydranet.utils.volume_sampler import VolumeSampler

        T, H, W, C = 10, 8, 8, 3
        rng = np.random.RandomState(42)
        data = rng.rand(T, H, W, C).astype(np.float32)
        channel_map = ["month_id", "priogrid_gid", "value"]

        handler = VolumeHandler(
            data=data,
            axes=("T", "H", "W", "C"),
            channel_map=channel_map,
            time_col="month_id",
            id_col="priogrid_gid",
            spatial_cols=("row", "col"),
        )

        cfg = {
            "window_dim": 4,
            "windows_per_lesson": 3,
            "np_seed": 42,
            "steps": [1, 2],
            "sampling_strategy": "power_law",
            "sampling_alpha": 1.5,
            "min_events": 1,
        }
        sampler = VolumeSampler(handler, cfg)
        batch, qualified = sampler.get_batch("value", threshold=1, batch_size=2)

        assert len(batch) == 2, f"Expected 2 windows, got {len(batch)}"
        for i, window in enumerate(batch):
            assert window.shape[1] == 4, f"Window {i} H mismatch"
            assert window.shape[2] == 4, f"Window {i} W mismatch"

