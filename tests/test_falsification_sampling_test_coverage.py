# P2: Sigmoid threshold recovery
# ---------------------------------------------------------------------------
class TestFalsifyP2SigmoidThresholdRecovery:
    """
    Probe 2 (Category E — Omission): Sigmoid threshold recovery.

    Finding: The plan specified a test that sigmoid with steepness→large
    should recover hard-threshold behaviour. This test was never implemented.
    Threshold recovery is the sigmoid strategy's key correctness property —
    it must degenerate to the threshold strategy in the limit.

    Severity: Soft falsification.

    Fix: Implement the threshold recovery test.
    """

    def test_sigmoid_high_steepness_recovers_threshold(self):
        """Sigmoid with very high steepness should behave like hard threshold.

        With steepness=100, cells well above threshold get ~uniform probability
        and cells well below threshold get ~0 probability, matching the
        threshold strategy's behaviour.
        """
        activity = np.zeros((H, W), dtype=np.int64)
        activity[0:8, 0:8] = 100  # well above threshold
        activity[0:8, 8:16] = 30  # well below threshold
        activity[8:16, 0:8] = 3  # below min_events

        cfg_sigmoid = {"sampling_steepness": 100.0}
        n = 2000

        samples_sigmoid = _sample_n(
            select_anchor_sigmoid, activity, THRESHOLD, MIN_EVENTS, cfg_sigmoid, n=n
        )
        samples_threshold = _sample_n(
            select_anchor_threshold, activity, THRESHOLD, MIN_EVENTS, {}, n=n
        )

        counts_sigmoid = _count_quadrants(samples_sigmoid)
        counts_threshold = _count_quadrants(samples_threshold)

        assert counts_sigmoid["top_left"] == n, (
            f"High-steepness sigmoid should select only above-threshold cells, "
            f"got {counts_sigmoid}"
        )
        assert counts_threshold["top_left"] == n, (
            f"Threshold baseline check failed, got {counts_threshold}"
        )


