# P1: Power-law discriminative power
# ---------------------------------------------------------------------------
class TestFalsifyP1PowerLawDiscriminativePower:
    """
    Probe 1 (Category H — Mutation): Power-law test discriminative power.

    Finding: 3 of 4 TestPowerLaw tests (concentration, medium_activity_included,
    seed_reproducibility) pass even when select_anchor_power_law is replaced
    with Boltzmann logic. Only alpha_increases_concentration catches the
    mutation because Boltzmann ignores sampling_alpha.

    Tests that cannot distinguish the correct implementation from a wrong
    one provide false confidence.

    Severity: Soft falsification.

    Fix: Add a test that verifies the power-law formula's defining property —
    that the probability ratio between two cells equals the activity ratio
    raised to the power alpha.
    """

    def test_power_law_ratio_matches_formula(self):
        """p(cell_a) / p(cell_b) ≈ (activity_a / activity_b)^alpha.

        With only two eligible cells, the probability ratio is fully
        determined by the formula. This test would FAIL if the implementation
        used Boltzmann (exp(activity/tau)) instead of power-law (activity^alpha).
        """
        activity = np.zeros((H, W), dtype=np.int64)
        activity[0, 0] = 100
        activity[1, 1] = 50

        alpha = 2.0
        cfg = {"sampling_alpha": alpha}
        n = 10000
        samples = _sample_n(select_anchor_power_law, activity, THRESHOLD, MIN_EVENTS, cfg, n=n)

        hits_100 = sum(1 for r, c in samples if (r, c) == (0, 0))
        hits_50 = sum(1 for r, c in samples if (r, c) == (1, 1))

        assert hits_50 > 0, "Both cells should be sampled"

        observed_ratio = hits_100 / hits_50
        expected_ratio = (100 / 50) ** alpha  # 4.0

        assert abs(observed_ratio - expected_ratio) < 1.5, (
            f"Power-law ratio should be ~{expected_ratio:.1f}, "
            f"got {observed_ratio:.1f} ({hits_100}/{hits_50})"
        )


